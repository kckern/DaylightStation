import QRCode from 'qrcode';

export const TI86_RESULT_QR_VERSION = 5;
export const TI86_RESULT_QR_SIZE = 37;
export const TI86_RESULT_QR_EC_LEVEL = 'M';
export const TI86_RESULT_QR_MASK = 0;
export const TI86_RESULT_QR_DATA_CODEWORDS = 86;
export const TI86_RESULT_QR_BLOCK_DATA_CODEWORDS = 43;
export const TI86_RESULT_QR_ECC_CODEWORDS = 24;
export const TI86_RESULT_QR_TOTAL_CODEWORDS = 134;
export const TI86_RESULT_QR_MAX_RECORD_BYTES = 69;
export const TI86_RESULT_QR_ORIGIN_X = 45;
export const TI86_RESULT_QR_ORIGIN_Y = 13;

const PREFIX = 'sch:r1:';
const BYTE_PREFIX = 'sch:r';
const ALPHANUMERIC = '0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ $%*+-./:';
const BASE32 = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ234567';

/**
 * Reference model for the deliberately fixed on-calculator QR profile.
 *
 * Fixed Version 5/M avoids a version-selection engine on the Z80 while still
 * fitting every compact v0 assessment/progress SCR1 (at most 69 raw bytes).
 * Mask 0 is valid QR; choosing a fixed mask avoids retaining eight matrices.
 */
export function createTi86ResultQrV5(record) {
  const bytes = asRecord(record);
  if (bytes.length > TI86_RESULT_QR_MAX_RECORD_BYTES) {
    throw new Error(`TI-86 result QR record exceeds ${TI86_RESULT_QR_MAX_RECORD_BYTES} bytes`);
  }
  const payload = `${PREFIX}${base32(bytes)}`;
  const dataCodewords = encodePayloadData(payload);
  const generator = generateGenerator(TI86_RESULT_QR_ECC_CODEWORDS);
  const errorCorrection = Buffer.concat([
    reedSolomon(dataCodewords.subarray(0, TI86_RESULT_QR_BLOCK_DATA_CODEWORDS), generator),
    reedSolomon(dataCodewords.subarray(TI86_RESULT_QR_BLOCK_DATA_CODEWORDS), generator),
  ]);
  const codewords = interleave(dataCodewords, errorCorrection);
  const structure = qrStructure();
  const modules = Uint8Array.from(structure.functionDark);
  let bitIndex = 0;
  let row = TI86_RESULT_QR_SIZE - 1;
  let direction = -1;
  for (let column = TI86_RESULT_QR_SIZE - 1; column > 0; column -= 2) {
    if (column === 6) column -= 1;
    for (;;) {
      for (let offset = 0; offset < 2; offset += 1) {
        const currentColumn = column - offset;
        const moduleIndex = row * TI86_RESULT_QR_SIZE + currentColumn;
        if (structure.reserved[moduleIndex]) continue;
        const source = bitIndex < codewords.length * 8
          ? (codewords[bitIndex >>> 3] >>> (7 - (bitIndex & 7))) & 1
          : 0;
        // QR mask pattern 0: (row + column) mod 2 == 0.
        modules[moduleIndex] = source ^ (((row + currentColumn) & 1) === 0 ? 1 : 0);
        bitIndex += 1;
      }
      row += direction;
      if (row < 0 || row >= TI86_RESULT_QR_SIZE) {
        row -= direction;
        direction = -direction;
        break;
      }
    }
  }
  if (bitIndex !== 1_079) throw new Error(`unexpected Version-5 data-module count ${bitIndex}`);

  const frame = Buffer.alloc(1024);
  for (let y = 0; y < TI86_RESULT_QR_SIZE; y += 1) {
    for (let x = 0; x < TI86_RESULT_QR_SIZE; x += 1) {
      if (!modules[y * TI86_RESULT_QR_SIZE + x]) continue;
      const frameX = TI86_RESULT_QR_ORIGIN_X + x;
      const frameY = TI86_RESULT_QR_ORIGIN_Y + y;
      frame[frameY * 16 + (frameX >>> 3)] |= 0x80 >>> (frameX & 7);
    }
  }
  return Object.freeze({
    payload,
    dataCodewords,
    errorCorrection,
    codewords,
    modules,
    frame,
  });
}

export function renderTi86ResultQrV5Assembly() {
  const { reserved, functionDark } = qrStructure();
  const generator = generateGenerator(TI86_RESULT_QR_ECC_CODEWORDS).subarray(1);
  return [
    '; Generated by tools/lib/ti86-result-qr-v5.mjs. Do not hand edit.',
    'scqr_reserved_bits:',
    ...assemblyBytes(packBits(reserved)),
    'scqr_function_dark_bits:',
    ...assemblyBytes(packBits(functionDark)),
    'scqr_rs_generator_tail:',
    ...assemblyBytes(generator),
    '',
  ].join('\n');
}

export function base32(input) {
  const bytes = asRecord(input);
  let output = '';
  let accumulator = 0;
  let bits = 0;
  for (const byte of bytes) {
    accumulator = (accumulator << 8) | byte;
    bits += 8;
    while (bits >= 5) {
      bits -= 5;
      output += BASE32[(accumulator >>> bits) & 31];
    }
  }
  if (bits > 0) output += BASE32[(accumulator << (5 - bits)) & 31];
  return output;
}

function encodePayloadData(payload) {
  if (!payload.startsWith(BYTE_PREFIX) || payload.slice(BYTE_PREFIX.length).split('').some((char) => !ALPHANUMERIC.includes(char))) {
    throw new Error('TI-86 result QR payload does not match its fixed Byte+Alphanumeric segmentation');
  }
  const bits = [];
  put(bits, 0b0100, 4); // Byte mode
  put(bits, BYTE_PREFIX.length, 8);
  for (const byte of Buffer.from(BYTE_PREFIX, 'ascii')) put(bits, byte, 8);
  const alpha = payload.slice(BYTE_PREFIX.length);
  put(bits, 0b0010, 4); // Alphanumeric mode
  put(bits, alpha.length, 9);
  for (let index = 0; index + 1 < alpha.length; index += 2) {
    put(bits, (ALPHANUMERIC.indexOf(alpha[index]) * 45) + ALPHANUMERIC.indexOf(alpha[index + 1]), 11);
  }
  if (alpha.length & 1) put(bits, ALPHANUMERIC.indexOf(alpha.at(-1)), 6);
  const capacity = TI86_RESULT_QR_DATA_CODEWORDS * 8;
  if (bits.length > capacity) throw new Error('TI-86 result QR payload exceeds Version 5/M');
  for (let index = 0; index < Math.min(4, capacity - bits.length); index += 1) bits.push(0);
  while (bits.length & 7) bits.push(0);
  const output = Buffer.alloc(TI86_RESULT_QR_DATA_CODEWORDS);
  for (let index = 0; index < bits.length; index += 1) {
    if (bits[index]) output[index >>> 3] |= 0x80 >>> (index & 7);
  }
  let byteIndex = bits.length >>> 3;
  let toggle = false;
  while (byteIndex < output.length) {
    output[byteIndex++] = toggle ? 0x11 : 0xec;
    toggle = !toggle;
  }
  return output;
}

function interleave(data, ecc) {
  const output = Buffer.alloc(TI86_RESULT_QR_TOTAL_CODEWORDS);
  let offset = 0;
  for (let index = 0; index < TI86_RESULT_QR_BLOCK_DATA_CODEWORDS; index += 1) {
    output[offset++] = data[index];
    output[offset++] = data[TI86_RESULT_QR_BLOCK_DATA_CODEWORDS + index];
  }
  for (let index = 0; index < TI86_RESULT_QR_ECC_CODEWORDS; index += 1) {
    output[offset++] = ecc[index];
    output[offset++] = ecc[TI86_RESULT_QR_ECC_CODEWORDS + index];
  }
  return output;
}

function reedSolomon(data, generator) {
  const remainder = Buffer.alloc(generator.length - 1);
  for (const byte of data) {
    const factor = byte ^ remainder[0];
    remainder.copyWithin(0, 1);
    remainder[remainder.length - 1] = 0;
    for (let index = 0; index < remainder.length; index += 1) {
      remainder[index] ^= gfMultiply(generator[index + 1], factor);
    }
  }
  return remainder;
}

function generateGenerator(degree) {
  let polynomial = Uint8Array.from([1]);
  let root = 1;
  for (let step = 0; step < degree; step += 1) {
    const next = new Uint8Array(polynomial.length + 1);
    polynomial.forEach((coefficient, index) => {
      next[index] ^= coefficient;
      next[index + 1] ^= gfMultiply(coefficient, root);
    });
    polynomial = next;
    root = gfMultiply(root, 2);
  }
  return polynomial;
}

function gfMultiply(left, right) {
  let a = left;
  let b = right;
  let result = 0;
  for (let bit = 0; bit < 8; bit += 1) {
    if (b & 1) result ^= a;
    a = (a << 1) ^ ((a & 0x80) ? 0x11d : 0);
    b >>>= 1;
  }
  return result;
}

let cachedStructure;
function qrStructure() {
  if (cachedStructure) return cachedStructure;
  const oracle = QRCode.create('sch:r1:A', {
    version: TI86_RESULT_QR_VERSION,
    errorCorrectionLevel: TI86_RESULT_QR_EC_LEVEL,
    maskPattern: TI86_RESULT_QR_MASK,
  });
  const reserved = Uint8Array.from(oracle.modules.reservedBit, (value) => value ? 1 : 0);
  const functionDark = Uint8Array.from(
    oracle.modules.data,
    (value, index) => reserved[index] && value ? 1 : 0,
  );
  cachedStructure = Object.freeze({ reserved, functionDark });
  return cachedStructure;
}

function packBits(bits) {
  const output = Buffer.alloc(Math.ceil(bits.length / 8));
  bits.forEach((bit, index) => {
    if (bit) output[index >>> 3] |= 0x80 >>> (index & 7);
  });
  return output;
}

function put(bits, value, width) {
  for (let shift = width - 1; shift >= 0; shift -= 1) bits.push((value >>> shift) & 1);
}

function assemblyBytes(bytes) {
  const lines = [];
  for (let offset = 0; offset < bytes.length; offset += 16) {
    lines.push(`        defb ${[...bytes.subarray(offset, offset + 16)]
      .map((byte) => `0x${byte.toString(16).padStart(2, '0')}`)
      .join(',')}`);
  }
  return lines;
}

function asRecord(input) {
  if (Buffer.isBuffer(input)) return input;
  if (input instanceof Uint8Array) return Buffer.from(input.buffer, input.byteOffset, input.byteLength);
  throw new Error('TI-86 result QR input must be SCR1 bytes');
}
