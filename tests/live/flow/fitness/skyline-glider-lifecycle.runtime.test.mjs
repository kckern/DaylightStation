import { test,expect } from '@playwright/test';
import path from 'node:path';
import os from 'node:os';
import {fileURLToPath} from 'node:url';
import { FRONTEND_URL } from '#fixtures/runtime/urls.mjs';
import { SkylineGliderCourseCatalog } from '../../../../__app_modules/wellness/fitness/server/adapters/SkylineGliderCourseCatalog.mjs';

test('shipped confidence course scrolls, responds, resumes and saves from bike controls',async({page})=>{
 test.setTimeout(120000);
 const courses=new SkylineGliderCourseCatalog({configService:{getHouseholdPath:relative=>path.join(os.tmpdir(),'skyline-acceptance-no-overrides',relative)}}).list('acceptance');
 let savedRun=null;
 await page.route('**/api/**',async route=>{
  const url=route.request().url();
  if(url.includes('/skyline-glider/courses'))return route.fulfill({json:{courses}});
  if(url.includes('/skyline-glider/world'))return route.fulfill({json:{next:'mountain-pass',zones:[{id:'alpine',acts:courses.map(c=>({id:c.id,name:c.name,status:'open'}))}]}});
  if(url.includes('/skyline-glider/runs')){savedRun=route.request().postDataJSON().record;return route.fulfill({status:201,json:{created:true}})}
  if(url.includes('/static/img/users/'))return route.fulfill({contentType:'image/svg+xml',body:'<svg xmlns="http://www.w3.org/2000/svg" width="80" height="80"><circle cx="40" cy="40" r="40" fill="#79dfed"/></svg>'});
  return route.fulfill({json:{}});
 });
 const press=(position,gesture='single')=>page.evaluate(({position,gesture})=>__skylineTest.press({action:position+'_'+gesture}),{position,gesture});
 const pedal=rpm=>page.evaluate(rpm=>__skylineTest.pedal(rpm),rpm);
 await page.clock.install();
 await page.goto(FRONTEND_URL+'/@fs'+fileURLToPath(new URL('../../../_fixtures/fitness/skyline-controls.html',import.meta.url)));
 const phase=()=>page.locator('[data-control-phase]');
 await expect(phase()).toHaveAttribute('data-control-phase','identity');
 await press(1);await press(4);await pedal(30);await page.clock.runFor(4500);
 await expect(phase()).toHaveAttribute('data-control-phase','flight');
 const geometry=page.locator('[data-testid="course-segment-valley-rise"] path').first();
 const first=await page.getByTestId('skyline-glider-flight').getAttribute('data-course-time');
 await page.clock.runFor(1500);
 expect(Number(await phase().getAttribute('data-course-time'))).toBeGreaterThan(Number(first));
 await pedal(130);await page.clock.runFor(1500);
 const high=await page.locator('.skyline-glider__craft').getAttribute('transform');
 await pedal(30);await page.clock.runFor(1500);
 expect(await page.locator('.skyline-glider__craft').getAttribute('transform')).not.toBe(high);
 await page.clock.runFor(15000);
 const checkpointTime=Number(await phase().getAttribute('data-course-time'));
 expect(checkpointTime).toBeGreaterThan(10);
 await page.reload();await expect(phase()).toHaveAttribute('data-control-phase','identity');
 await press(1);
 await expect(page.getByRole('button',{name:/Resume/})).toBeVisible();
 await press(4);await pedal(30);await page.clock.runFor(4500);
 await expect(phase()).toHaveAttribute('data-control-phase','flight');
 expect(Number(await phase().getAttribute('data-course-time'))).toBeGreaterThan(checkpointTime-3);
 await press(4,'hold');await press(3);
 await expect(page.getByText(/Flight saved/)).toBeVisible();
 expect(savedRun.run).toMatchObject({status:'abandoned',course_id:'mountain-pass',course_version:6,equipment_id:'test-bike'});
 expect(savedRun.result.schema).toBe('gaming-result/v1');
 expect((await page.evaluate(()=>__skylineTest.snapshot())).awards).toEqual([]);
});
