#!/usr/bin/env node
/**
 * Generate a maximum-density, single-screen TI-86 quiz-result QR frame.
 *
 * The payload is deliberately QR-alphanumeric (colon-separated, not CSV),
 * allowing Version 9/M to hold 262 characters. Answer digits are 0=blank,
 * 1=A, 2=B, 3=C, 4=D.  The default result holds 238 responses.
 *
 * Usage: node _extensions/ti86-app/tools/generate-quiz-result.mjs
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import QRCode from 'qrcode';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const WIDTH = 128;
const HEIGHT = 64;
const BYTES_PER_ROW = WIDTH / 8;
const VERSION = 9;
const EC = 'M';
const QUIET = 4;
const SCALE = 1;

// CRC-16/CCITT-FALSE: compact, deterministic protection against bad scans.
function crc16(text) {
  let crc = 0xFFFF;
  for (const byte of Buffer.from(text, 'ascii')) {
    crc ^= byte << 8;
    for (let bit = 0; bit < 8; bit += 1) crc = (crc & 0x8000) ? ((crc << 1) ^ 0x1021) & 0xFFFF : (crc << 1) & 0xFFFF;
  }
  return crc.toString(16).toUpperCase().padStart(4, '0');
}

// Fixed demonstration results: 238 answers, generated deterministically so
// the payload is reproducible. Production code will use actual key input.
let state = 0x86A1;
const answers = Array.from({ length: 238 }, () => {
  state = (state * 109 + 1021) & 0xFFFF;
  return String((state % 4) + 1);
}).join('');
// QMX is a capacity-test pack, deliberately distinct from School's real
// QK1 lesson (which has ten answers and uses calculator:pack:sequence order).
const body = `DS1:R:T86A:QMX:001:${answers}`;
const payload = `${body}:${crc16(body)}`;

if (payload.length !== 262) throw new Error(`payload must fill V9/M (got ${payload.length} characters)`);
const qr = QRCode.create(payload, { version: VERSION, errorCorrectionLevel: EC });
if (qr.modules.size !== 53) throw new Error(`expected Version 9 (53 modules), got ${qr.modules.size}`);
if (qr.modules.size * SCALE + 2 * QUIET > HEIGHT) throw new Error('QR does not fit TI-86 LCD height');

const frame = new Uint8Array(BYTES_PER_ROW * HEIGHT);
const originX = Math.floor((WIDTH - (qr.modules.size + 2 * QUIET)) / 2) + QUIET;
const originY = Math.floor((HEIGHT - (qr.modules.size + 2 * QUIET)) / 2) + QUIET;
function setPixel(x, y) { frame[y * BYTES_PER_ROW + Math.floor(x / 8)] |= 0x80 >> (x & 7); }

for (let row = 0; row < qr.modules.size; row += 1) {
  for (let col = 0; col < qr.modules.size; col += 1) {
    if (qr.modules.get(row, col)) setPixel(originX + col, originY + row);
  }
}

const hex = (value) => `$${value.toString(16).padStart(2, '0').toUpperCase()}`;
const lines = [];
for (let offset = 0; offset < frame.length; offset += 16) {
  lines.push(`    .db ${[...frame.slice(offset, offset + 16)].map(hex).join(', ')}`);
}
const out = path.join(__dirname, '..', 'src', 'generated', 'qr-frame.inc');
mkdirSync(path.dirname(out), { recursive: true });
writeFileSync(out, [
  `; Generated by tools/generate-quiz-result.mjs — payload (${payload.length} QR alphanumeric chars):`,
  `; ${payload}`,
  '; Version 9 / EC-M / 53×53 modules / 1× scale / 4-module quiet zone.',
  'QR_FRAME:', ...lines, '',
].join('\n'));
console.log(`[ti86] wrote ${out}`);
console.log(`[ti86] V9/M, 61×61 pixels including quiet zone, ${payload.length} chars / 238 answers`);
console.log(`[ti86] payload=${payload}`);
