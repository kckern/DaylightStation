#!/usr/bin/env node
/** Build the TI-86 paged SchoolCalc typed-record reader probe. */
import {
  mkdtempSync,
  mkdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { Ti86SchoolCalcCodec } from '../../../backend/src/1_adapters/schoolcalc/ti86/Ti86SchoolCalcCodec.mjs';
import {
  createTi86AsmProgram,
  TI86_ASM_EXEC_RAM,
  TI86_VIDEO_RAM,
} from './lib/ti86-program.mjs';
import {
  loadSchoolCalcUiAssets,
  renderSchoolCalcUiAssembly,
} from './lib/schoolcalc-ui-assets.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const EXTENSION = path.resolve(HERE, '..');
const SOURCE_DIRECTORY = path.join(EXTENSION, 'src');
const SOURCE = path.join(SOURCE_DIRECTORY, 'record-reader-probe.asm');
const GENERATED = path.join(SOURCE_DIRECTORY, 'generated', 'record-reader-probe-data.inc');
const GENERATED_UI = path.join(SOURCE_DIRECTORY, 'generated', 'ui-assets.inc');
const OUTPUT = path.join(EXTENSION, 'dist', 'SCREAD.86p');

const artifact = new Ti86SchoolCalcCodec().compile(sampleBundle());
const uiAssets = loadSchoolCalcUiAssets(EXTENSION);
mkdirSync(path.dirname(GENERATED), { recursive: true });
writeFileSync(GENERATED, renderProbeData(artifact.bytes));
writeFileSync(GENERATED_UI, renderSchoolCalcUiAssembly(uiAssets));

const buildDirectory = mkdtempSync(path.join(tmpdir(), 'schoolcalc-reader-z80-'));
const rawBinary = path.join(buildDirectory, 'record-reader-probe.bin');
try {
  const result = spawnSync('z80asm', [
    '-I', SOURCE_DIRECTORY,
    '-o', rawBinary,
    SOURCE,
  ], { encoding: 'utf8' });
  if (result.error?.code === 'ENOENT') throw new Error('z80asm is required; install it with `brew install z80asm`');
  if (result.status !== 0) throw new Error(`z80asm failed:\n${result.stdout}${result.stderr}`);
  const code = readFileSync(rawBinary);
  if (TI86_ASM_EXEC_RAM + code.length > TI86_VIDEO_RAM) {
    throw new Error(`SCREAD overlaps Video RAM by ${TI86_ASM_EXEC_RAM + code.length - TI86_VIDEO_RAM} bytes`);
  }
  const file = createTi86AsmProgram({
    name: 'SCREAD', code, comment: 'SchoolCalc paged record reader probe',
  });
  mkdirSync(path.dirname(OUTPUT), { recursive: true });
  writeFileSync(OUTPUT, file);
  console.log(`[ti86] built ${OUTPUT} (${file.length} bytes; code ${code.length} bytes)`);
  console.log(`[ti86] embedded ${artifact.bytes.length}-byte ${artifact.variableName}/SCP1 fixture; valid + corrupt checks`);
} finally {
  rmSync(buildDirectory, { recursive: true, force: true });
}

function sampleBundle() {
  return {
    schema: 'school.learning-lesson/v1',
    address: 'probe/catalog/course/unit/lesson',
    context: {
      catalog: { catalogId: 'probe', title: 'Probe Catalog' },
      subject: { subjectId: 'subject', title: 'Subject' },
      course: { courseId: 'course', title: 'Course' },
      unit: { unitId: 'unit', title: 'Unit' },
    },
    lesson: {
      lessonId: 'lesson',
      title: 'Reader probe',
      objectives: ['Validate a paged typed record'],
      modules: [{
        moduleId: 'notes',
        type: 'lecture_notes',
        documentId: 'probe-notes',
        document: {
          schema: 'school.learning-document/v1',
          documentId: 'probe-notes',
          title: 'Probe notes',
          blocks: [{
            blockId: 'runtime-content', type: 'prose',
            text: 'Runtime content remains structured text.',
          }],
        },
      }],
    },
    capabilities: ['reader@1'],
  };
}

function renderProbeData(record) {
  return [
    '; Generated by tools/build-record-reader-probe.mjs. Do not hand edit.',
    'probe_record:',
    ...assemblyBytes(record),
    `PROBE_RECORD_LENGTH: equ ${record.length}`,
    '',
  ].join('\n');
}

function assemblyBytes(bytes) {
  const lines = [];
  for (let offset = 0; offset < bytes.length; offset += 16) {
    lines.push(`        defb ${[...bytes.subarray(offset, offset + 16)]
      .map((byte) => `0x${byte.toString(16).padStart(2, '0')}`)
      .join(',')}`);
  }
  return lines;
}
