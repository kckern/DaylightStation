#!/usr/bin/env node
// Build a Skyline Glider zone from a gaming-assets skin.
//
//   node __app_modules/wellness/fitness/cli/skyline-skin.cli.mjs build --skin <skin.yml> --zone-id <id>
//        [--name <name>] [--base-zone alpine] [--root <games/_common>] [--media <media dir>]
//   node __app_modules/wellness/fitness/cli/skyline-skin.cli.mjs brief [--base-zone alpine] [--out brief.yml]
//   node __app_modules/wellness/fitness/cli/skyline-skin.cli.mjs world --world <world-build.yml> [--out-dir <dir>]
//        builds every level's zone from its skin and its act from its course recipe, validates each act with
//        the game's course model, and writes world.yml + zones/ + courses/ (the household layout).
//   node __app_modules/wellness/fitness/cli/skyline-skin.cli.mjs install --zone-id <id> --zones-dir <household zones dir>
//        [--media <media dir>] [--private-dev true]
//
// build: validates and exports the skin into media/fitness/skyline-glider/<zone-id>/
// and writes zone.yml beside it (art from the skin, gameplay from the base zone).
// install: copies that zone.yml into the household zones folder, where the game
// loads it. Both build and install point the zone's sounds at its own sound set,
// media/fitness/skyline-glider/_sounds/<zone-id>/<slot>.<ext>, for every slot
// file found there; slots without a file keep the base zone's sound. A private-only skin (placeholder art) is refused unless --private-dev
// true is given, because installed zones appear on every rider's world map.

import { spawnSync } from 'node:child_process';
import { copyFile, mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import YAML from 'yaml';
import { buildSkinBrief, exportSkin } from '../../../../__capabilities/gaming/cli/gaming-assets/skins.mjs';
import { zoneFromSkinExport } from '../server/adapters/skylineGlider/skinZone.mjs';
import { buildCourseFromRecipe } from '../server/adapters/skylineGlider/courseRecipe.mjs';
import { resolveAct } from '../server/adapters/skylineGlider/resolveAct.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const ADAPTERS = path.resolve(here, '../server/adapters/skylineGlider');
export const CONTRACT = path.join(ADAPTERS, 'skin-contract.yml');
const ZONE_ID = /^[a-z0-9][a-z0-9-]*$/;

function parse(argv) {
  const [command, ...rest] = argv;
  const flags = {};
  for (let index = 0; index < rest.length; index += 2) {
    if (!rest[index]?.startsWith('--') || rest[index + 1] === undefined) throw new Error(`bad argument near ${rest[index]}`);
    flags[rest[index].slice(2)] = rest[index + 1];
  }
  return { command, flags };
}

const mediaDir = (flags, env) => path.resolve(flags.media ?? path.join(env.DAYLIGHT_BASE_PATH ?? '', 'media'));
const zoneDir = (media, id) => path.join(media, 'fitness', 'skyline-glider', id);
const SOUND_SETS = 'fitness/skyline-glider/_sounds';

/**
 * A zone's own sound set: { slot: media-rooted path } for each file in
 * media/fitness/skyline-glider/_sounds/<zoneId>/ named after a sound slot, in
 * slot order. Null when the folder is absent or holds no slot file.
 */
export async function zoneSoundSet(media, zoneId) {
  const { SKYLINE_SOUND_SLOTS } = await import('../browser/lib/skylineGlider/skylineAudio.js');
  let files;
  try { files = (await readdir(path.join(media, ...SOUND_SETS.split('/'), zoneId))).sort(); }
  catch (error) { if (error.code === 'ENOENT') return null; throw error; }
  const set = {};
  for (const slot of SKYLINE_SOUND_SLOTS) {
    const file = files.find((name) => path.parse(name).name === slot && path.parse(name).ext);
    if (file) set[slot] = `/${SOUND_SETS}/${zoneId}/${file}`;
  }
  return Object.keys(set).length ? set : null;
}

/** The zone's sounds with its own sound set laid over them, slot by slot. */
function withSoundSet(zoneSounds, set) {
  if (!set) return zoneSounds;
  const rest = Object.entries(zoneSounds ?? {}).filter(([slot]) => !(slot in set));
  return { ...set, ...Object.fromEntries(rest) };
}

export async function build({ skinPath, zoneId, name, baseZone = 'alpine', root, media }) {
  if (!ZONE_ID.test(zoneId ?? '')) throw new Error('--zone-id must be a lowercase slug');
  const outDir = zoneDir(media, zoneId);
  const exported = await exportSkin({ root, contractPath: CONTRACT, skinPath, outDir });
  if (!exported.ok) return { ok: false, errors: exported.errors };
  const base = YAML.parse(await readFile(path.join(ADAPTERS, 'zones', `${baseZone}.yml`), 'utf8'));
  const contract = YAML.parse(await readFile(CONTRACT, 'utf8'));
  const zone = zoneFromSkinExport(exported.manifest, { baseZone: base, id: zoneId, name, assetRoot: `fitness/skyline-glider/${zoneId}`, artPixel: contract.units?.art_pixel ?? 2, sceneHeight: contract.units?.height ?? 600, sounds: await zoneSoundSet(media, zoneId) });
  const header = `# Generated by skyline-skin.cli.mjs from skin ${exported.manifest.skin} (${exported.manifest.distribution}).\n# Art: gaming-assets skin export in this folder. Gameplay: zones/${baseZone}.yml. Do not edit; rebuild.\n`;
  await writeFile(path.join(outDir, 'zone.yml'), header + YAML.stringify(zone));
  return { ok: true, outDir, zone: zoneId, distribution: exported.manifest.distribution, slots: Object.keys(exported.manifest.slots), warnings: exported.warnings };
}

/** The commissioning brief for a zone: every slot's limits, with entity boxes from the base zone. */
export async function brief({ baseZone = 'alpine' } = {}) {
  const contract = YAML.parse(await readFile(CONTRACT, 'utf8'));
  const base = YAML.parse(await readFile(path.join(ADAPTERS, 'zones', `${baseZone}.yml`), 'utf8'));
  const unitsPerSecond = (contract.units?.width ?? 1000) / 14;
  const entityBoxes = Object.fromEntries(Object.entries(base.entities ?? {}).map(([name, def]) => [name, [Math.round(Number(def.width_s ?? 0.5) * unitsPerSecond), Math.round(Number(def.height ?? 0.1) * (contract.units?.height ?? 600))]]));
  return buildSkinBrief(contract, { entityBoxes });
}

/**
 * A whole world from one config file: every level is a zone (built from a skin)
 * and an act (generated from a course recipe), in play order. Every act is
 * resolved onto its zone and validated by the game's own course model.
 *
 *   schema: skyline-glider-world-build/v1
 *   id: smw-placeholder
 *   levels:
 *     - { zone: green-hills, skin: smw-placeholder, name: Green Hills,
 *         course: { style: bells, difficulty: easy, duration_s: 180, seed: 1 } }
 */
export async function buildWorld({ worldPath, root, media, outDir }) {
  const { validateCourse } = await import('../browser/lib/skylineGlider/courseModel.js');
  const world = YAML.parse(await readFile(worldPath, 'utf8'));
  if (world?.schema !== 'skyline-glider-world-build/v1') return { ok: false, errors: ['world schema must be skyline-glider-world-build/v1'] };
  const out = outDir ?? path.join(media, 'fitness', 'skyline-glider', '_worlds', world.id);
  await mkdir(path.join(out, 'zones'), { recursive: true });
  await mkdir(path.join(out, 'courses'), { recursive: true });
  const errors = []; const levels = []; const zoneOrder = []; const actIndex = new Map();
  for (const [index, level] of (world.levels ?? []).entries()) {
    const label = `level ${index + 1} (${level.zone})`;
    if (!zoneOrder.includes(level.zone)) {
      const built = await build({ skinPath: path.resolve(root, level.skin_path ?? `catalog/skins/skyline-glider/${level.skin}.yml`), zoneId: level.zone, name: level.zone_name ?? level.name, root, media });
      if (!built.ok) { errors.push(`${label}: ${built.errors.join('; ')}`); continue; }
      await copyFile(path.join(zoneDir(media, level.zone), 'zone.yml'), path.join(out, 'zones', `${level.zone}.yml`));
      zoneOrder.push(level.zone);
    }
    const act = (actIndex.get(level.zone) ?? 0) + 1; actIndex.set(level.zone, act);
    const id = level.id ?? `${level.zone}-${level.course?.style ?? 'course'}`;
    let course;
    try { course = buildCourseFromRecipe({ schema: 'skyline-glider-recipe/v1', id, name: level.name, description: level.description, zone: level.zone, act, ...level.course }); }
    catch (error) { errors.push(`${label}: ${error.message}`); continue; }
    const zone = YAML.parse(await readFile(path.join(out, 'zones', `${level.zone}.yml`), 'utf8'));
    const checked = validateCourse(resolveAct(course, new Map([[level.zone, zone]])));
    if (!checked.valid) { errors.push(`${label}: course invalid: ${checked.errors.join('; ')}`); continue; }
    await writeFile(path.join(out, 'courses', `${id}.yml`), `# Generated by skyline-skin.cli.mjs world from ${path.basename(worldPath)}. Do not edit; change the recipe.\n${YAML.stringify(course)}`);
    levels.push({ level: index + 1, zone: level.zone, act, id, style: course.generated_from.style, difficulty: course.generated_from.difficulty });
  }
  await writeFile(path.join(out, 'world.yml'), YAML.stringify({ schema: 'skyline-glider-world/v1', zones: zoneOrder }));
  return { ok: errors.length === 0, out, levels, errors };
}

export async function install({ zoneId, zonesDir, media, privateDev = false }) {
  const source = path.join(zoneDir(media, zoneId), 'zone.yml');
  const text = await readFile(source, 'utf8');
  const zone = YAML.parse(text);
  if (zone.skin?.distribution !== 'shippable' && !privateDev) {
    return { ok: false, errors: [`zone ${zoneId} uses a ${zone.skin?.distribution ?? 'unknown'} skin; installed zones appear on every rider's world map. Pass --private-dev true only on a development data tree.`] };
  }
  await mkdir(zonesDir, { recursive: true });
  const target = path.join(zonesDir, `${zoneId}.yml`);
  // A zone.yml built before its sound set existed still points at the base
  // zone's sounds; installing it must not reset the zone to them.
  const set = await zoneSoundSet(media, zoneId);
  if (set) {
    const header = text.match(/^(?:#[^\n]*\n)*/)[0];
    await writeFile(target, header + YAML.stringify({ ...zone, sounds: withSoundSet(zone.sounds, set) }));
  } else await copyFile(source, target);
  return { ok: true, installed: target, distribution: zone.skin?.distribution, sounds: set ? `${SOUND_SETS}/${zoneId}` : 'base zone' };
}

export async function main(argv = process.argv.slice(2), env = process.env, { stdout = process.stdout, stderr = process.stderr } = {}) {
  try {
    const { command, flags } = parse(argv);
    const media = mediaDir(flags, env);
    let result;
    if (command === 'build') {
      result = await build({
        skinPath: path.resolve(flags.skin ?? ''), zoneId: flags['zone-id'], name: flags.name, baseZone: flags['base-zone'] ?? 'alpine',
        root: path.resolve(flags.root ?? path.join(media, 'games', '_common')), media,
      });
    } else if (command === 'world') {
      result = await buildWorld({ worldPath: path.resolve(flags.world ?? ''), root: path.resolve(flags.root ?? path.join(media, 'games', '_common')), media, outDir: flags['out-dir'] ? path.resolve(flags['out-dir']) : undefined });
    } else if (command === 'brief') {
      const out = await brief({ baseZone: flags['base-zone'] ?? 'alpine' });
      if (flags.out) await writeFile(flags.out, YAML.stringify(out));
      result = { ok: true, ...(flags.out ? { out: flags.out, slots: out.slots.length } : out) };
    } else if (command === 'install') {
      if (!flags['zones-dir']) throw new Error('--zones-dir is required');
      result = await install({ zoneId: flags['zone-id'], zonesDir: path.resolve(flags['zones-dir']), media, privateDev: flags['private-dev'] === 'true' });
    } else {
      stderr.write('usage: skyline-skin.cli.mjs build|brief|install (see header)\n');
      return 2;
    }
    stdout.write(`${JSON.stringify(result, null, 2)}\n`);
    return result.ok ? 0 : 1;
  } catch (error) {
    stderr.write(`ERROR: ${error.message}\n`);
    return 2;
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  // The game's browser modules (course model, sound slots) are ES modules in .js files; Node 20 needs module detection to load them.
  if (['world', 'build', 'install'].includes(process.argv[2]) && !process.execArgv.includes('--experimental-detect-module')) {
    const child = spawnSync(process.execPath, ['--experimental-detect-module', ...process.execArgv, ...process.argv.slice(1)], { stdio: 'inherit' });
    process.exitCode = child.status ?? 1;
  } else main().then((code) => { process.exitCode = code; });
}
