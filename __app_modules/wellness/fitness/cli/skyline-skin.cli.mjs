#!/usr/bin/env node
// Build a Skyline Glider zone from a gaming-assets skin.
//
//   node __app_modules/wellness/fitness/cli/skyline-skin.cli.mjs build --skin <skin.yml> --zone-id <id>
//        [--name <name>] [--base-zone alpine] [--root <games/_common>] [--media <media dir>]
//   node __app_modules/wellness/fitness/cli/skyline-skin.cli.mjs install --zone-id <id> --zones-dir <household zones dir>
//        [--media <media dir>] [--private-dev true]
//
// build: validates and exports the skin into media/fitness/skyline-glider/<zone-id>/
// and writes zone.yml beside it (art from the skin, gameplay from the base zone).
// install: copies that zone.yml into the household zones folder, where the game
// loads it. A private-only skin (placeholder art) is refused unless --private-dev
// true is given, because installed zones appear on every rider's world map.

import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import YAML from 'yaml';
import { exportSkin } from '../../../../__capabilities/gaming/cli/gaming-assets/skins.mjs';
import { zoneFromSkinExport } from '../server/adapters/skylineGlider/skinZone.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const ADAPTERS = path.resolve(here, '../server/adapters/skylineGlider');
export const CONTRACT = path.join(ADAPTERS, 'skin-contract.yml');
const ZONE_ID = /^[a-z0-9][a-z0-9-]*$/;

function parse(argv) {
  const [command, ...rest] = argv;
  const flags = {};
  for (let index = 0; index < rest.length; index += 2) {
    if (!rest[index]?.startsWith('--') || rest[index + 1] === undefined) throw new Error(`bad argument near ${rest[index]}`);
    flags[rest[index].slice(2)] = rest[index + 1];
  }
  return { command, flags };
}

const mediaDir = (flags, env) => path.resolve(flags.media ?? path.join(env.DAYLIGHT_BASE_PATH ?? '', 'media'));
const zoneDir = (media, id) => path.join(media, 'fitness', 'skyline-glider', id);

export async function build({ skinPath, zoneId, name, baseZone = 'alpine', root, media }) {
  if (!ZONE_ID.test(zoneId ?? '')) throw new Error('--zone-id must be a lowercase slug');
  const outDir = zoneDir(media, zoneId);
  const exported = await exportSkin({ root, contractPath: CONTRACT, skinPath, outDir });
  if (!exported.ok) return { ok: false, errors: exported.errors };
  const base = YAML.parse(await readFile(path.join(ADAPTERS, 'zones', `${baseZone}.yml`), 'utf8'));
  const contract = YAML.parse(await readFile(CONTRACT, 'utf8'));
  const zone = zoneFromSkinExport(exported.manifest, { baseZone: base, id: zoneId, name, assetRoot: `fitness/skyline-glider/${zoneId}`, artPixel: contract.units?.art_pixel ?? 3, sceneHeight: contract.units?.height ?? 600 });
  const header = `# Generated by skyline-skin.cli.mjs from skin ${exported.manifest.skin} (${exported.manifest.distribution}).\n# Art: gaming-assets skin export in this folder. Gameplay: zones/${baseZone}.yml. Do not edit; rebuild.\n`;
  await writeFile(path.join(outDir, 'zone.yml'), header + YAML.stringify(zone));
  return { ok: true, outDir, zone: zoneId, distribution: exported.manifest.distribution, slots: Object.keys(exported.manifest.slots), warnings: exported.warnings };
}

export async function install({ zoneId, zonesDir, media, privateDev = false }) {
  const source = path.join(zoneDir(media, zoneId), 'zone.yml');
  const zone = YAML.parse(await readFile(source, 'utf8'));
  if (zone.skin?.distribution !== 'shippable' && !privateDev) {
    return { ok: false, errors: [`zone ${zoneId} uses a ${zone.skin?.distribution ?? 'unknown'} skin; installed zones appear on every rider's world map. Pass --private-dev true only on a development data tree.`] };
  }
  await mkdir(zonesDir, { recursive: true });
  const target = path.join(zonesDir, `${zoneId}.yml`);
  await copyFile(source, target);
  return { ok: true, installed: target, distribution: zone.skin?.distribution };
}

export async function main(argv = process.argv.slice(2), env = process.env, { stdout = process.stdout, stderr = process.stderr } = {}) {
  try {
    const { command, flags } = parse(argv);
    const media = mediaDir(flags, env);
    let result;
    if (command === 'build') {
      result = await build({
        skinPath: path.resolve(flags.skin ?? ''), zoneId: flags['zone-id'], name: flags.name, baseZone: flags['base-zone'] ?? 'alpine',
        root: path.resolve(flags.root ?? path.join(media, 'games', '_common')), media,
      });
    } else if (command === 'install') {
      if (!flags['zones-dir']) throw new Error('--zones-dir is required');
      result = await install({ zoneId: flags['zone-id'], zonesDir: path.resolve(flags['zones-dir']), media, privateDev: flags['private-dev'] === 'true' });
    } else {
      stderr.write('usage: skyline-skin.cli.mjs build|install (see header)\n');
      return 2;
    }
    stdout.write(`${JSON.stringify(result, null, 2)}\n`);
    return result.ok ? 0 : 1;
  } catch (error) {
    stderr.write(`ERROR: ${error.message}\n`);
    return 2;
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  main().then((code) => { process.exitCode = code; });
}
